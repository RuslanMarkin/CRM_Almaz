import { useState, useMemo } from "react";
import { ArrowRight, Calculator, CheckCircle2, ChevronDown, ChevronUp, FileText, Plus, Sparkles, Trash2, TrendingUp, Truck } from "lucide-react";
import { toast } from "sonner";

export interface DealDeskSubmission {
  deal: {
    number: string;
    sellerId: number;
    buyerId: number;
    carrierId: number | null;
    cargoName: string;
    cargoGrade?: string;
    plannedVolume?: string;
    purchasePrice?: string;
    salePrice?: string;
    currency: string;
    startDate?: string;
    endDate?: string;
    status: "planning" | "active" | "closing" | "completed" | "cancelled";
    notes?: string;
  };
  carrierTariff: string;
  autoGenerateDocuments: boolean;
  loadingAddress: string;
  unloadingAddress: string;
  specificationIds: number[];
}

interface Counterparty {
  id: number;
  name: string;
  shortName?: string | null;
  businessRole?: string | null;
  vatType?: string | null;
  loadingAddress?: string | null;
  actualAddress?: string | null;
}

interface SpecificationItem {
  specification: {
    id: number;
    number: string;
    contractId: number;
    dealId?: number | null;
    cargoName?: string | null;
    pricePerUnit?: string | null;
  };
}

interface ContractItem {
  contract: {
    id: number;
    number: string;
    contractKind?: string | null;
  };
}

interface DealDeskModalProps {
  open: boolean;
  onClose: () => void;
  editingDealId?: number | null;
  initialDeal?: {
    number: string;
    sellerId: string;
    buyerId: string;
    carrierId: string;
    cargoName: string;
    cargoGrade: string;
    plannedVolume: string;
    purchasePrice: string;
    salePrice: string;
    carrierTariff?: string;
    currency: string;
    startDate: string;
    endDate: string;
    status: "planning" | "active" | "closing" | "completed" | "cancelled";
    notes: string;
    specificationIds?: number[];
  };
  counterparties: Counterparty[];
  specifications: SpecificationItem[];
  contracts: ContractItem[];
  saving: boolean;
  deleting?: boolean;
  onSubmit: (params: DealDeskSubmission) => Promise<void>;
  onDelete?: () => void;
  onOpenCreateCounterparty?: (role: "seller" | "buyer" | "carrier") => void;
}

const COMMON_CROPS = [
  "Пшеница продовольственная 3 класс",
  "Пшеница продовольственная 4 класс",
  "Пшеница фуражная",
  "Ячмень пивоваренный",
  "Ячмень фуражный",
  "Кукуруза фуражная",
  "Горох продовольственный",
  "Подсолнечник масличный",
  "Соя товарная",
  "Рапс яровой",
];

export function DealDeskModal({
  open,
  onClose,
  editingDealId,
  initialDeal,
  counterparties,
  specifications,
  contracts,
  saving,
  deleting = false,
  onSubmit,
  onDelete,
  onOpenCreateCounterparty,
}: DealDeskModalProps) {
  // Form State
  const defaultNumber = useMemo(() => {
    const year = new Date().getFullYear();
    const rand = Math.floor(100 + Math.random() * 900);
    return `СД-${year}/${rand}`;
  }, []);

  const [number, setNumber] = useState(initialDeal?.number || defaultNumber);
  const [cargoName, setCargoName] = useState(initialDeal?.cargoName || "Пшеница продовольственная 3 класс");
  const [cargoGrade, setCargoGrade] = useState(initialDeal?.cargoGrade || "ГОСТ 9353-2016");
  const [plannedVolume, setPlannedVolume] = useState(initialDeal?.plannedVolume || "200");
  const [purchasePrice, setPurchasePrice] = useState(initialDeal?.purchasePrice || "14000");
  const [carrierTariff, setCarrierTariff] = useState(initialDeal?.carrierTariff || "1500");
  const [salePrice, setSalePrice] = useState(initialDeal?.salePrice || "17000");
  const [sellerId, setSellerId] = useState(initialDeal?.sellerId || "");
  const [buyerId, setBuyerId] = useState(initialDeal?.buyerId || "");
  const [carrierId, setCarrierId] = useState(initialDeal?.carrierId || "");
  const [startDate, setStartDate] = useState(initialDeal?.startDate || new Date().toISOString().split("T")[0]);
  const [endDate, setEndDate] = useState(initialDeal?.endDate || "");
  const [status, setStatus] = useState<"planning" | "active" | "closing" | "completed" | "cancelled">(
    initialDeal?.status || "active"
  );
  const [notes, setNotes] = useState(initialDeal?.notes || "");
  const [loadingAddress, setLoadingAddress] = useState("");
  const [unloadingAddress, setUnloadingAddress] = useState("");
  const [autoGenerateDocuments, setAutoGenerateDocuments] = useState(!editingDealId);
  const [showAdvancedSpecs, setShowAdvancedSpecs] = useState(false);
  const [selectedSpecIds, setSelectedSpecIds] = useState<number[]>(initialDeal?.specificationIds || []);

  // Filtered counterparties
  const sellers = useMemo(() => counterparties.filter((c) => c.businessRole === "seller"), [counterparties]);
  const buyers = useMemo(() => counterparties.filter((c) => c.businessRole === "buyer"), [counterparties]);
  const carriers = useMemo(() => counterparties.filter((c) => c.businessRole === "carrier"), [counterparties]);

  // Handle seller selection -> auto-fill loading address
  const handleSellerChange = (id: string) => {
    setSellerId(id);
    const seller = counterparties.find((c) => String(c.id) === id);
    if (seller && (seller.loadingAddress || seller.actualAddress)) {
      setLoadingAddress(seller.loadingAddress || seller.actualAddress || "");
    }
  };

  // Handle buyer selection -> auto-fill unloading address
  const handleBuyerChange = (id: string) => {
    setBuyerId(id);
    const buyer = counterparties.find((c) => String(c.id) === id);
    if (buyer && (buyer.actualAddress || buyer.loadingAddress)) {
      setUnloadingAddress(buyer.actualAddress || buyer.loadingAddress || "");
    }
  };

  // Unit-economics calculation
  const volumeNum = Number(plannedVolume) || 0;
  const purchasePriceNum = Number(purchasePrice) || 0;
  const carrierTariffNum = Number(carrierTariff) || 0;
  const salePriceNum = Number(salePrice) || 0;

  // Formula from whiteboard: M = (Дог П. - ТТН - Дог З.) / Тонн
  const revenueTotal = volumeNum * salePriceNum;
  const purchaseTotal = volumeNum * purchasePriceNum;
  const logisticsTotal = volumeNum * carrierTariffNum;
  const costsTotal = purchaseTotal + logisticsTotal;
  const marginPerTon = salePriceNum - carrierTariffNum - purchasePriceNum;
  const netProfit = marginPerTon * volumeNum;
  const marginPercent = revenueTotal > 0 ? ((netProfit / revenueTotal) * 100).toFixed(1) : "0.0";

  const isProfitable = marginPerTon > 0;
  const isLoss = marginPerTon < 0;

  async function handleFormSubmit() {
    if (!number.trim()) {
      toast.error("Укажите номер сделки");
      return;
    }
    if (!sellerId) {
      toast.error("Выберите продавца (поставщика)");
      return;
    }
    if (!buyerId) {
      toast.error("Выберите покупателя (экспортёра/завод)");
      return;
    }
    if (!cargoName.trim()) {
      toast.error("Укажите наименование товара");
      return;
    }
    if (volumeNum <= 0) {
      toast.error("Укажите корректный объём партии");
      return;
    }

    try {
      await onSubmit({
        deal: {
          number: number.trim(),
          sellerId: Number(sellerId),
          buyerId: Number(buyerId),
          carrierId: carrierId ? Number(carrierId) : null,
          cargoName: cargoName.trim(),
          cargoGrade: cargoGrade.trim() || undefined,
          plannedVolume: plannedVolume || undefined,
          purchasePrice: purchasePrice || undefined,
          salePrice: salePrice || undefined,
          currency: "RUB",
          startDate: startDate || undefined,
          endDate: endDate || undefined,
          status,
          notes: notes.trim() || undefined,
        },
        carrierTariff,
        autoGenerateDocuments,
        loadingAddress,
        unloadingAddress,
        specificationIds: selectedSpecIds,
      });
    } catch (e: any) {
      toast.error(e?.message || "Ошибка при сохранении сделки");
    }
  }

  if (!open) return null;

  return (
    <div className="agro-dialog-backdrop" role="presentation" onMouseDown={onClose}>
      <section
        className="agro-dialog"
        role="dialog"
        aria-modal="true"
        aria-label="Конструктор сделки (Deal Desk)"
        style={{ width: "min(1160px, 98vw)", maxHeight: "94vh", padding: "28px" }}
        onMouseDown={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="agro-dialog-head" style={{ marginBottom: "18px" }}>
          <div>
            <div style={{ display: "flex", alignItems: "center", gap: "8px", marginBottom: "4px" }}>
              <span className="agro-dialog-kicker">Единая точка входа · Deal Desk</span>
              <span
                style={{
                  background: "rgba(14, 124, 114, 0.12)",
                  color: "var(--soil)",
                  fontSize: "10.5px",
                  fontWeight: 700,
                  padding: "2px 8px",
                  borderRadius: "12px",
                  textTransform: "uppercase",
                  letterSpacing: "0.5px",
                }}
              >
                Торговый хаб
              </span>
            </div>
            <h2 style={{ fontSize: "26px", margin: 0 }}>
              {editingDealId ? `Редактирование сделки № ${number}` : "Проведение новой сделки"}
            </h2>
          </div>
          <button
            type="button"
            className="agro-icon-button"
            onClick={onClose}
            aria-label="Закрыть форму"
            title="Закрыть"
          >
            ×
          </button>
        </div>

        {/* Live Margin Bar (Unit-economics formula from whiteboard) */}
        <div
          style={{
            background: isLoss ? "#FEF2F2" : isProfitable ? "#F0FDF4" : "#F9FAFB",
            border: `1.5px solid ${isLoss ? "#FCA5A5" : isProfitable ? "#86EFAC" : "#E5E7EB"}`,
            borderRadius: "12px",
            padding: "16px 20px",
            marginBottom: "22px",
            boxShadow: "0 2px 8px rgba(0,0,0,0.03)",
          }}
        >
          <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "10px" }}>
            <div style={{ display: "flex", alignItems: "center", gap: "6px", fontSize: "12px", fontWeight: 700, color: "var(--soil)" }}>
              <Calculator size={15} style={{ color: "var(--wheat)" }} />
              <span>ЮНИТ-ЭКОНОМИКА СДЕЛКИ:</span>
              <code style={{ background: "rgba(0,0,0,0.05)", padding: "2px 6px", borderRadius: "4px", fontSize: "11.5px", fontFamily: "monospace" }}>
                M = (Дог П. - ТТН - Дог З.) / Тонн
              </code>
            </div>
            <div style={{ fontSize: "11.5px", color: isLoss ? "#DC2626" : isProfitable ? "#16A34A" : "var(--soil-soft)", fontWeight: 600 }}>
              {isLoss ? "Внимание: сделка убыточна!" : isProfitable ? `Рентабельность: +${marginPercent}%` : "Заполните цены"}
            </div>
          </div>

          <div
            style={{
              display: "grid",
              gridTemplateColumns: "repeat(auto-fit, minmax(170px, 1fr))",
              gap: "14px",
              alignItems: "center",
            }}
          >
            {/* Volume */}
            <div style={{ padding: "8px 12px", background: "#fff", borderRadius: "8px", border: "1px solid var(--line)" }}>
              <div style={{ fontSize: "11px", color: "var(--soil-soft)", textTransform: "uppercase" }}>Партия</div>
              <div style={{ fontSize: "18px", fontWeight: 700, color: "var(--soil)" }}>
                {volumeNum.toLocaleString("ru-RU")} т
              </div>
            </div>

            {/* Sale Revenue */}
            <div style={{ padding: "8px 12px", background: "#fff", borderRadius: "8px", border: "1px solid var(--line)" }}>
              <div style={{ fontSize: "11px", color: "var(--soil-soft)", textTransform: "uppercase" }}>Выручка (Дог П.)</div>
              <div style={{ fontSize: "18px", fontWeight: 700, color: "#1D4ED8" }}>
                {revenueTotal.toLocaleString("ru-RU")} ₽
              </div>
              <div style={{ fontSize: "10.5px", color: "var(--soil-soft)" }}>{salePriceNum.toLocaleString("ru-RU")} ₽/т</div>
            </div>

            {/* Costs Breakdown */}
            <div style={{ padding: "8px 12px", background: "#fff", borderRadius: "8px", border: "1px solid var(--line)" }}>
              <div style={{ fontSize: "11px", color: "var(--soil-soft)", textTransform: "uppercase" }}>Затраты (З + ТТН)</div>
              <div style={{ fontSize: "18px", fontWeight: 700, color: "var(--soil)" }}>
                {costsTotal.toLocaleString("ru-RU")} ₽
              </div>
              <div style={{ fontSize: "10.5px", color: "var(--soil-soft)" }}>
                З: {purchasePriceNum.toLocaleString("ru-RU")} + Лог: {carrierTariffNum.toLocaleString("ru-RU")} ₽/т
              </div>
            </div>

            {/* Margin M per ton */}
            <div
              style={{
                padding: "8px 14px",
                background: isLoss ? "#FEE2E2" : isProfitable ? "#DCFCE7" : "#F3F4F6",
                borderRadius: "8px",
                border: `1px solid ${isLoss ? "#F87171" : isProfitable ? "#4ADE80" : "#D1D5DB"}`,
              }}
            >
              <div style={{ fontSize: "11px", color: isLoss ? "#991B1B" : isProfitable ? "#166534" : "#4B5563", textTransform: "uppercase", fontWeight: 700 }}>
                МАРЖА (M) на тонну
              </div>
              <div style={{ fontSize: "20px", fontWeight: 800, color: isLoss ? "#DC2626" : isProfitable ? "#15803D" : "#374151" }}>
                {marginPerTon >= 0 ? "+" : ""}
                {marginPerTon.toLocaleString("ru-RU")} ₽/т
              </div>
              <div style={{ fontSize: "11px", fontWeight: 700, color: isLoss ? "#DC2626" : isProfitable ? "#15803D" : "#374151" }}>
                Прибыль: {netProfit >= 0 ? "+" : ""}
                {netProfit.toLocaleString("ru-RU")} ₽
              </div>
            </div>
          </div>
        </div>

        {/* 3 Core Workflow Columns: Закупка -> Логистика -> Продажа */}
        <div
          style={{
            display: "grid",
            gridTemplateColumns: "repeat(auto-fit, minmax(320px, 1fr))",
            gap: "18px",
            marginBottom: "20px",
          }}
        >
          {/* ═════════ 1. ЗАКУПКА (Поставщик) ═════════ */}
          <div
            style={{
              background: "#FAF9F5",
              border: "1px solid #E5DFD3",
              borderRadius: "10px",
              padding: "16px",
              display: "flex",
              flexDirection: "column",
              gap: "12px",
            }}
          >
            <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", borderBottom: "1px solid #E5DFD3", paddingBottom: "8px" }}>
              <div style={{ display: "flex", alignItems: "center", gap: "6px", fontWeight: 700, fontSize: "13px", color: "var(--soil)" }}>
                <span style={{ width: "20px", height: "20px", borderRadius: "50%", background: "var(--wheat)", color: "#fff", display: "grid", placeItems: "center", fontSize: "11px" }}>
                  1
                </span>
                <span>ЗАКУПКА (Поставщик)</span>
              </div>
              <span className="agro-tag">Договор закупки</span>
            </div>

            {/* Seller Select */}
            <div>
              <div style={{ display: "flex", justifyContent: "space-between", marginBottom: "4px" }}>
                <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)" }}>
                  Продавец (КФХ / Элеватор) *
                </label>
                {onOpenCreateCounterparty && (
                  <button
                    type="button"
                    onClick={() => onOpenCreateCounterparty("seller")}
                    style={{ background: "none", border: 0, padding: 0, color: "var(--wheat)", fontSize: "11px", cursor: "pointer", textDecoration: "underline" }}
                  >
                    + Новый
                  </button>
                )}
              </div>
              <select
                value={sellerId}
                onChange={(e) => handleSellerChange(e.target.value)}
                style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "13px" }}
              >
                <option value="">Выберите продавца</option>
                {sellers.map((s) => (
                  <option key={s.id} value={s.id}>
                    {s.shortName || s.name} ({s.vatType === "without_vat" ? "Без НДС" : "С НДС"})
                  </option>
                ))}
              </select>
            </div>

            {/* Crop & Grade */}
            <div>
              <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                Товар / Культура *
              </label>
              <input
                list="crop-list"
                value={cargoName}
                onChange={(e) => setCargoName(e.target.value)}
                placeholder="Например, Пшеница 3 класс"
                style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "13px" }}
              />
              <datalist id="crop-list">
                {COMMON_CROPS.map((c) => (
                  <option key={c} value={c} />
                ))}
              </datalist>
            </div>

            {/* Volume & Purchase Price */}
            <div style={{ display: "grid", gridTemplateColumns: "1fr 1.2fr", gap: "10px" }}>
              <div>
                <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                  Объём, т *
                </label>
                <input
                  type="number"
                  value={plannedVolume}
                  onChange={(e) => setPlannedVolume(e.target.value)}
                  placeholder="200"
                  style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "13px", fontWeight: 600 }}
                />
              </div>
              <div>
                <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                  Цена закупки, ₽/т *
                </label>
                <input
                  type="number"
                  value={purchasePrice}
                  onChange={(e) => setPurchasePrice(e.target.value)}
                  placeholder="14000"
                  style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "13px", fontWeight: 600 }}
                />
              </div>
            </div>

            {/* Loading Address */}
            <div>
              <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                Базис / пункт погрузки
              </label>
              <input
                value={loadingAddress}
                onChange={(e) => setLoadingAddress(e.target.value)}
                placeholder="Склад хозяйства, элеватор"
                style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "12.5px" }}
              />
            </div>
          </div>

          {/* ═════════ 2. ЛОГИСТИКА (Перевозка) ═════════ */}
          <div
            style={{
              background: "#F5F8F7",
              border: "1px solid #D8E5E1",
              borderRadius: "10px",
              padding: "16px",
              display: "flex",
              flexDirection: "column",
              gap: "12px",
            }}
          >
            <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", borderBottom: "1px solid #D8E5E1", paddingBottom: "8px" }}>
              <div style={{ display: "flex", alignItems: "center", gap: "6px", fontWeight: 700, fontSize: "13px", color: "var(--soil)" }}>
                <span style={{ width: "20px", height: "20px", borderRadius: "50%", background: "#0E7C72", color: "#fff", display: "grid", placeItems: "center", fontSize: "11px" }}>
                  2
                </span>
                <span>ЛОГИСТИКА (Доставка)</span>
              </div>
              <span className="agro-tag" style={{ background: "#E0F2FE", color: "#0369A1" }}>ТТН и рейсы</span>
            </div>

            {/* Carrier Select */}
            <div>
              <div style={{ display: "flex", justifyContent: "space-between", marginBottom: "4px" }}>
                <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)" }}>
                  Перевозчик / Логистика
                </label>
                {onOpenCreateCounterparty && (
                  <button
                    type="button"
                    onClick={() => onOpenCreateCounterparty("carrier")}
                    style={{ background: "none", border: 0, padding: 0, color: "var(--wheat)", fontSize: "11px", cursor: "pointer", textDecoration: "underline" }}
                  >
                    + Новый
                  </button>
                )}
              </div>
              <select
                value={carrierId}
                onChange={(e) => setCarrierId(e.target.value)}
                style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "13px" }}
              >
                <option value="">Пул перевозчиков (помашинно в ТТН)</option>
                {carriers.map((c) => (
                  <option key={c.id} value={c.id}>
                    {c.shortName || c.name} (основной)
                  </option>
                ))}
              </select>
              <span style={{ fontSize: "10px", color: "var(--soil-soft)", marginTop: "4px", display: "block", lineHeight: 1.3 }}>
                По одному договору привлекается множество перевозчиков. Конкретный перевозчик, авто и водитель указываются в каждой выписанной ТТН.
              </span>
            </div>

            {/* Carrier Tariff */}
            <div>
              <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                Тариф перевозки, ₽/т *
              </label>
              <input
                type="number"
                value={carrierTariff}
                onChange={(e) => setCarrierTariff(e.target.value)}
                placeholder="1500"
                style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "13px", fontWeight: 600 }}
              />
              <span style={{ fontSize: "10.5px", color: "var(--soil-soft)", marginTop: "3px", display: "block" }}>
                Плановые затраты на ТТН: <b>{logisticsTotal.toLocaleString("ru-RU")} ₽</b>
              </span>
            </div>

            {/* Route preview */}
            <div style={{ padding: "10px", background: "#fff", borderRadius: "6px", border: "1px solid var(--line)" }}>
              <div style={{ fontSize: "11px", color: "var(--soil-soft)", textTransform: "uppercase", marginBottom: "4px" }}>
                Маршрут движения
              </div>
              <div style={{ display: "flex", alignItems: "center", gap: "6px", fontSize: "12px", color: "var(--soil)" }}>
                <span className="truncate" style={{ maxWidth: "120px" }}>
                  {loadingAddress || "Погрузка"}
                </span>
                <ArrowRight size={14} style={{ color: "var(--wheat)", flexShrink: 0 }} />
                <span className="truncate" style={{ maxWidth: "120px" }}>
                  {unloadingAddress || "Выгрузка"}
                </span>
              </div>
            </div>
          </div>

          {/* ═════════ 3. ПРОДАЖА (Покупатель) ═════════ */}
          <div
            style={{
              background: "#F5F8FB",
              border: "1px solid #D6E4F0",
              borderRadius: "10px",
              padding: "16px",
              display: "flex",
              flexDirection: "column",
              gap: "12px",
            }}
          >
            <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", borderBottom: "1px solid #D6E4F0", paddingBottom: "8px" }}>
              <div style={{ display: "flex", alignItems: "center", gap: "6px", fontWeight: 700, fontSize: "13px", color: "var(--soil)" }}>
                <span style={{ width: "20px", height: "20px", borderRadius: "50%", background: "#1D4ED8", color: "#fff", display: "grid", placeItems: "center", fontSize: "11px" }}>
                  3
                </span>
                <span>ПРОДАЖА (Покупатель)</span>
              </div>
              <span className="agro-tag" style={{ background: "#EFF6FF", color: "#1D4ED8" }}>Договор продажи</span>
            </div>

            {/* Buyer Select */}
            <div>
              <div style={{ display: "flex", justifyContent: "space-between", marginBottom: "4px" }}>
                <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)" }}>
                  Покупатель (Экспортёр / МЭЗ) *
                </label>
                {onOpenCreateCounterparty && (
                  <button
                    type="button"
                    onClick={() => onOpenCreateCounterparty("buyer")}
                    style={{ background: "none", border: 0, padding: 0, color: "var(--wheat)", fontSize: "11px", cursor: "pointer", textDecoration: "underline" }}
                  >
                    + Новый
                  </button>
                )}
              </div>
              <select
                value={buyerId}
                onChange={(e) => handleBuyerChange(e.target.value)}
                style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "13px" }}
              >
                <option value="">Выберите покупателя</option>
                {buyers.map((b) => (
                  <option key={b.id} value={b.id}>
                    {b.shortName || b.name} ({b.vatType === "without_vat" ? "Без НДС" : "С НДС"})
                  </option>
                ))}
              </select>
            </div>

            {/* Sale Price */}
            <div>
              <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                Цена реализации, ₽/т *
              </label>
              <input
                type="number"
                value={salePrice}
                onChange={(e) => setSalePrice(e.target.value)}
                placeholder="17000"
                style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "13px", fontWeight: 600 }}
              />
              <span style={{ fontSize: "10.5px", color: "var(--soil-soft)", marginTop: "3px", display: "block" }}>
                Итого к получению: <b>{revenueTotal.toLocaleString("ru-RU")} ₽</b>
              </span>
            </div>

            {/* Unloading Address */}
            <div>
              <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                Базис / пункт приёмки
              </label>
              <input
                value={unloadingAddress}
                onChange={(e) => setUnloadingAddress(e.target.value)}
                placeholder="Портовый терминал, элеватор"
                style={{ width: "100%", padding: "8px 10px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "12.5px" }}
              />
            </div>

            {/* Deal Dates */}
            <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: "10px" }}>
              <div>
                <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                  Дата начала
                </label>
                <input
                  type="date"
                  value={startDate}
                  onChange={(e) => setStartDate(e.target.value)}
                  style={{ width: "100%", padding: "7px 8px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "12px" }}
                />
              </div>
              <div>
                <label style={{ fontSize: "11px", textTransform: "uppercase", fontWeight: 700, color: "var(--soil-soft)", display: "block", marginBottom: "4px" }}>
                  Срок окончания
                </label>
                <input
                  type="date"
                  value={endDate}
                  onChange={(e) => setEndDate(e.target.value)}
                  style={{ width: "100%", padding: "7px 8px", borderRadius: "6px", border: "1px solid var(--line)", background: "#fff", fontSize: "12px" }}
                />
              </div>
            </div>
          </div>
        </div>

        {/* Smart Document Automation Banner */}
        <div
          style={{
            background: "rgba(14, 124, 114, 0.06)",
            border: "1px solid rgba(14, 124, 114, 0.2)",
            borderRadius: "8px",
            padding: "12px 16px",
            marginBottom: "18px",
            display: "flex",
            alignItems: "center",
            justifyContent: "space-between",
          }}
        >
          <div style={{ display: "flex", alignItems: "center", gap: "10px" }}>
            <input
              type="checkbox"
              id="auto-gen"
              checked={autoGenerateDocuments}
              onChange={(e) => setAutoGenerateDocuments(e.target.checked)}
              style={{ width: "18px", height: "18px", accentColor: "var(--soil)", cursor: "pointer" }}
            />
            <label htmlFor="auto-gen" style={{ cursor: "pointer" }}>
              <strong style={{ fontSize: "13px", color: "var(--soil)", display: "block" }}>
                Автоматически сформировать пакет документов для этой сделки
              </strong>
              <span style={{ fontSize: "11.5px", color: "var(--soil-soft)" }}>
                Система сама создаст договор закупки, договор продажи, спецификации и привяжет их к сделке.
              </span>
            </label>
          </div>
          <Sparkles size={18} style={{ color: "var(--wheat)", flexShrink: 0 }} />
        </div>

        {/* Optional Manual Spec Linking (Accordion) */}
        <div style={{ marginBottom: "16px" }}>
          <button
            type="button"
            onClick={() => setShowAdvancedSpecs(!showAdvancedSpecs)}
            style={{
              background: "none",
              border: 0,
              padding: "4px 0",
              color: "var(--soil-soft)",
              fontSize: "12px",
              cursor: "pointer",
              display: "flex",
              alignItems: "center",
              gap: "4px",
            }}
          >
            <span>Связать существующие спецификации вручную</span>
            {showAdvancedSpecs ? <ChevronUp size={14} /> : <ChevronDown size={14} />}
          </button>

          {showAdvancedSpecs && (
            <div style={{ marginTop: "10px", maxHeight: "160px", overflowY: "auto", border: "1px solid var(--line)", borderRadius: "6px", padding: "10px" }}>
              {!specifications.length ? (
                <div style={{ fontSize: "12px", color: "var(--soil-soft)" }}>Спецификаций в базе пока нет</div>
              ) : (
                specifications.map((item) => {
                  const contract = contracts.find((row) => row.contract.id === item.specification.contractId)?.contract;
                  const isChecked = selectedSpecIds.includes(item.specification.id);
                  return (
                    <label key={item.specification.id} style={{ display: "flex", alignItems: "center", gap: "8px", padding: "4px 0", fontSize: "12px", cursor: "pointer" }}>
                      <input
                        type="checkbox"
                        checked={isChecked}
                        onChange={() => {
                          setSelectedSpecIds(
                            isChecked ? selectedSpecIds.filter((id) => id !== item.specification.id) : [...selectedSpecIds, item.specification.id]
                          );
                        }}
                      />
                      <span>
                        <b>№ {item.specification.number}</b> · {item.specification.cargoName || "Товар не указан"}{" "}
                        <span style={{ color: "var(--soil-soft)" }}>({contract ? `Договор № ${contract.number}` : "Без договора"})</span>
                      </span>
                    </label>
                  );
                })
              )}
            </div>
          )}
        </div>

        {/* Footer */}
        <div
          className="agro-dialog-footer"
          style={{
            borderTop: "1px solid var(--line)",
            paddingTop: "14px",
            display: "flex",
            justifyContent: editingDealId && onDelete ? "space-between" : "flex-end",
            alignItems: "center",
            flexWrap: "wrap",
            gap: "10px",
          }}
        >
          {editingDealId && onDelete && (
            <button
              type="button"
              className="agro-btn ghost"
              onClick={onDelete}
              disabled={saving || deleting}
              style={{
                color: "#DC2626",
                borderColor: "#FCA5A5",
                display: "inline-flex",
                alignItems: "center",
                gap: "6px",
              }}
            >
              <Trash2 size={15} />
              <span>{deleting ? "Удаление..." : "Удалить сделку"}</span>
            </button>
          )}
          <div style={{ display: "flex", gap: "10px", marginLeft: "auto" }}>
            <button type="button" className="agro-btn ghost" onClick={onClose} disabled={saving || deleting}>
              Отмена
            </button>
            <button
              type="button"
              className="agro-btn"
              disabled={saving || deleting}
              onClick={handleFormSubmit}
              style={{
                background: isLoss ? "#DC2626" : "var(--soil)",
                display: "flex",
                alignItems: "center",
                gap: "8px",
                padding: "10px 22px",
                fontWeight: 700,
              }}
            >
              <span>{saving ? "Сохранение..." : editingDealId ? "Сохранить изменения" : "Запустить сделку"}</span>
            </button>
          </div>
        </div>
      </section>
    </div>
  );
}
