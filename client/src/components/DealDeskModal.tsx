export function getNextDealNumber(existingDeals: { number?: string }[] = []): string {
  const year = new Date().getFullYear();
  const prefix = `СД-${year}/`;
  let maxSeq = 0;

  for (const d of existingDeals) {
    const num = d?.number;
    if (!num) continue;
    if (num.startsWith(prefix)) {
      const suffix = num.slice(prefix.length);
      const parsed = parseInt(suffix, 10);
      if (!isNaN(parsed) && parsed > maxSeq) {
        maxSeq = parsed;
      }
    }
  }

  const nextVal = maxSeq + 1;
  const formattedSuffix = nextVal < 10 ? `0${nextVal}` : `${nextVal}`;
  return `${prefix}${formattedSuffix}`;
}

